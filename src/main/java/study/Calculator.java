package study;

public class Calculator {
    // 혼자 만들면서 만들었던 객체입니다. 이후 ttd 버전에 오버플로우, 언더플로우에 대한 수정을 진행하였습니다.
    int add(int i, int j) {
        return i + j;
    }

    int subtract(int i, int j) {
        return i - j;
    }

    int multiply(int i, int j) {
        return i * j;
    }

    int divide(int i, int j) {
        return i / j;
    }
}
